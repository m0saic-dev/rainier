#!/usr/bin/env node
/**
 * bake-font-metrics — write a font's advance widths + kerning pairs into a
 * TypeScript table a template can measure with.
 *
 *   node tools/bake-font-metrics.mjs [--out <file.ts>]
 *
 * WHY: the renderer's `drawtext` draws with a SYSTEM font (fontconfig), but
 * a word-by-word reveal places every word as its own layer — so the template
 * has to know how wide each word will come out, exactly. The bundled fonts in
 * @m0saic/text are not what drawtext draws with, so we measure the real one
 * (Helvetica Neue Regular, macOS) once, here, and commit the numbers: the
 * template stays deterministic and ships no font file (metrics only).
 *
 * macOS-only dev tool (reads /System/Library/Fonts/HelveticaNeue.ttc). The
 * output is committed; hosts never run this.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const outArg = argv.indexOf("--out");
const OUT = path.resolve(
  ROOT,
  outArg >= 0 ? argv[outArg + 1] : "src/reels/lyric-triptych/v1/font-metrics.ts",
);

const FONT = { family: "Helvetica Neue", subfamily: "Regular", file: "/System/Library/Fonts/HelveticaNeue.ttc" };

/** Pull one face out of a TrueType Collection (opentype.js 1.x reads single fonts only). */
function facesOf(buf) {
  const dirs = buf.toString("ascii", 0, 4) === "ttcf"
    ? Array.from({ length: buf.readUInt32BE(8) }, (_, i) => buf.readUInt32BE(12 + i * 4))
    : [0];
  return dirs.map((dir) => {
    const n = buf.readUInt16BE(dir + 4);
    const tables = Array.from({ length: n }, (_, i) => {
      const r = dir + 12 + i * 16;
      return { tag: buf.toString("ascii", r, r + 4), sum: buf.readUInt32BE(r + 4), off: buf.readUInt32BE(r + 8), len: buf.readUInt32BE(r + 12) };
    });
    let size = 12 + n * 16;
    for (const t of tables) size += (t.len + 3) & ~3;
    const out = Buffer.alloc(size);
    buf.copy(out, 0, dir, dir + 12);
    let at = 12 + n * 16;
    tables.forEach((t, i) => {
      const r = 12 + i * 16;
      out.write(t.tag, r, "ascii");
      out.writeUInt32BE(t.sum, r + 4);
      out.writeUInt32BE(at, r + 8);
      out.writeUInt32BE(t.len, r + 12);
      buf.copy(out, at, t.off, t.off + t.len);
      at += (t.len + 3) & ~3;
    });
    return opentype.parse(out.buffer.slice(out.byteOffset, out.byteOffset + out.byteLength));
  });
}

const font = facesOf(fs.readFileSync(FONT.file)).find(
  (f) => f.names.fontFamily?.en === FONT.family && f.names.fontSubfamily?.en === FONT.subfamily,
);
if (!font) {
  console.error(`bake-font-metrics: ${FONT.family} ${FONT.subfamily} not found in ${FONT.file}`);
  process.exit(1);
}

// Printable ASCII, Latin-1, and the typographic punctuation lyrics use.
const chars = [];
for (let c = 0x20; c <= 0x7e; c++) chars.push(String.fromCharCode(c));
for (let c = 0xa1; c <= 0xff; c++) chars.push(String.fromCharCode(c));
for (const ch of "‘’‚“”„–—…•·′″€") chars.push(ch);

const glyphs = chars.map((ch) => [ch, font.charToGlyph(ch)]).filter(([, g]) => g && g.index !== 0);
const advances = Object.fromEntries(glyphs.map(([ch, g]) => [ch, g.advanceWidth]));
const kerning = {};
for (const [a, ga] of glyphs) {
  for (const [b, gb] of glyphs) {
    const k = font.getKerningValue(ga, gb);
    if (k) kerning[a + b] = k;
  }
}
const os2 = font.tables.os2 ?? {};

const body = `/**
 * GENERATED by tools/bake-font-metrics.mjs — do not edit by hand.
 *
 * ${FONT.family} ${FONT.subfamily}: advance widths and kerning pairs, in font
 * units (${font.unitsPerEm} per em). These are the numbers ffmpeg's drawtext
 * lays the same font out with, so a word placed at a measured x lands exactly
 * where one long drawtext string would have put it. Metrics only — no glyphs,
 * no font file.
 */
export const FONT_METRICS = {
  family: ${JSON.stringify(FONT.family)},
  unitsPerEm: ${font.unitsPerEm},
  ascender: ${font.ascender},
  descender: ${font.descender},
  capHeight: ${os2.sCapHeight ?? Math.round(font.ascender * 0.72)},
  xHeight: ${os2.sxHeight ?? Math.round(font.ascender * 0.53)},
  /** Advance for a character the table does not cover (≈ the "o"). */
  fallbackAdvance: ${advances.o ?? Math.round(font.unitsPerEm * 0.56)},
  advances: ${JSON.stringify(advances)} as Record<string, number>,
  kerning: ${JSON.stringify(kerning)} as Record<string, number>,
} as const;
`;
fs.writeFileSync(OUT, body);
console.log(
  `bake-font-metrics: ${FONT.family} ${FONT.subfamily} -> ${path.relative(ROOT, OUT)} ` +
    `(${Object.keys(advances).length} advances, ${Object.keys(kerning).length} kerning pairs)`,
);
